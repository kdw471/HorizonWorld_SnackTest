/**
 * 기획 CSV 의 색 코드 -> 구현 색상 enum.
 * 기획은 R O Y G B I(인디고) V(바이올렛) P 8종, 구현도 8종이라 1:1 대응한다.
 * (인디고/바이올렛은 구현의 CYAN/PURPLE 슬롯을 쓴다. 실제 색은 메쉬가 정한다)
 */
const COLOR_BY_LETTER: { [letter: string]: EFlowColor } = {
	R: EFlowColor.RED,
	O: EFlowColor.ORANGE,
	Y: EFlowColor.YELLOW,
	G: EFlowColor.GREEN,
	B: EFlowColor.BLUE,
	I: EFlowColor.CYAN,
	V: EFlowColor.PURPLE,
	P: EFlowColor.PINK,
};

function decodeLevel(raw: string): FlowFieldTableEntry {
	const parts = raw.split('|');
	const puzzleId = parts[0];
	// 인덱스 10자리 = 80 + 0 + 퍼즐(2) + 난이도(2) + 순서(3)
	const difficulty = parseInt(puzzleId.substring(5, 7), 10);
	const map = parts[1];

	const tileBitmap: string[] = [];
	const nodes: FlowNode[] = [];
	const colors: EFlowColor[] = [];
	let mainCount = 0;
	let subCount = 0;

	for (let row = 0; row < FLOW_GRID_SIZE; row++) {
		let bits = '';
		for (let col = 0; col < FLOW_GRID_SIZE; col++) {
			const symbol = map.charAt(row * FLOW_GRID_SIZE + col);
			if (symbol === '.') {
				bits += '0';
				continue;
			}
			bits += '1';

			if (symbol === '#') {
				nodes.push({ row: row, col: col, kind: ENodeKind.SUB });
				subCount++;
				continue;
			}

			// 대문자 = 출발, 소문자 = 도착
			const isStart = symbol === symbol.toUpperCase();
			const color = COLOR_BY_LETTER[symbol.toUpperCase()];
			nodes.push({
				row: row,
				col: col,
				kind: ENodeKind.MAIN,
				color: color,
				role: isStart ? ENodeRole.START : ENodeRole.END,
			});
			mainCount++;
			if (isStart && colors.indexOf(color) < 0) {
				colors.push(color);
			}
		}
		tileBitmap.push(bits);
	}

	return {
		puzzleId: puzzleId,
		difficulty: difficulty,
		tileBitmap: tileBitmap,
		nodes: nodes,
		mainCount: mainCount,
		subCount: subCount,
		colorCount: colors.length,
	};
}

/** 기획 CSV 에서 뽑은 연결 퍼즐 필드 테이블 (120판) */
export const FLOW_CSV_FIELD_TABLE: FlowFieldTableEntry[] = RAW_LEVELS.map(decodeLevel);

/**
 * 방향 전환 딜레이(초). 기획 CSV 에 없는 값이라 난이도별로 여기서 준다 - §6.
 * 난이도가 올라갈수록 바늘이 빨라지므로 딜레이도 조금씩 늘린다.
 */
const REVERSE_DELAY_BY_DIFFICULTY: number[] = [0.3, 0.3, 0.35, 0.35, 0.4, 0.4];

function decodeLevel(raw: string): ColorFillFieldTableEntry {
	const parts = raw.split('|');
	const puzzleId = parts[0];
	// 인덱스 10자리 = 80 + 0 + 퍼즐(2) + 난이도(2) + 순서(3)
	const difficulty = parseInt(puzzleId.substring(5, 7), 10);

	const slots: DialSlot[] = [];
	let contaminatedCount = 0;
	for (let index = 0; index < DIAL_SLOT_COUNT; index++) {
		const isContaminated = parts[1].charAt(index) === '1';
		if (isContaminated) {
			contaminatedCount++;
		}
		slots.push({
			index: index,
			// 활성 영역 == 오염 영역 (원본에 "활성이지만 깨끗한 칸" 정보가 없다)
			isActive: isContaminated,
			state: isContaminated ? ESlotState.CONTAMINATED : ESlotState.CLEAN,
		});
	}

	return {
		puzzleId: puzzleId,
		difficulty: difficulty,
		slots: slots,
		needleSpeedDegPerSec: parseInt(parts[2], 10),
		reverseDelaySeconds: REVERSE_DELAY_BY_DIFFICULTY[difficulty - 1] ?? 0.4,
		startAngleDeg: 0,
		contaminatedCount: contaminatedCount,
	};
}

/** 기획 CSV 에서 뽑은 색 채우기 필드 테이블 (164판) */
export const COLORFILL_CSV_FIELD_TABLE: ColorFillFieldTableEntry[] = RAW_LEVELS.map(decodeLevel);
